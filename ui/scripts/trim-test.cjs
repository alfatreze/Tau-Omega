// Settings > Syncing music > Skip silence: off by default, the choices and their defaults, saved to the preferences.
// Usage: (npm run dev &) && NODE_PATH=$(npm root -g) node scripts/trim-test.cjs
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const url = process.env.URL || 'http://localhost:5173';
let passed = 0;
const ok = (n) => { passed++; console.log(`ok - ${n}`); };
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  p.on('pageerror', (e) => errors.push(e.message));
  p.on('console', (m) => m.text().startsWith('[dev-mock] unmocked') && errors.push(m.text()));
  await p.goto(url); await p.evaluate(() => localStorage.clear()); await p.goto(url); await p.waitForTimeout(800);
  await p.getByRole('button', { name: /Tools & settings/ }).click(); await p.getByRole('button', { name: 'Settings', exact: true }).click(); await p.waitForTimeout(500);
  const fs = p.locator('fieldset', { hasText: 'Skip silence at the start and end' });
  assert.equal(await fs.count(), 1);
  assert.equal(await fs.getByLabel('Silence level').count(), 0); ok('skip silence is off by default and shows no options');
  await fs.getByRole('button', { name: 'Turn on' }).click(); await p.waitForTimeout(300);
  assert.equal(await fs.getByLabel('Silence level').inputValue(), '-600'); ok('on: the level starts at -60 dB');
  assert.equal(await fs.getByLabel('Silence kept at the start').inputValue(), '200');
  assert.equal(await fs.getByLabel('Silence kept at the end').inputValue(), '500');
  assert.equal(await fs.getByLabel('Smallest silence').inputValue(), '2000'); ok('the defaults: keep 200 ms before and 500 ms after, skip silences of at least 2 s');
  const levels = await fs.getByLabel('Silence level').locator('option').allTextContents();
  assert.equal(levels[0].trim(), '-80 dB'); assert.match(levels.join('|'), /-60 dB \(default\)/); assert.equal(levels.length, 9); ok('the level is limited to -80 to -40 dB');
  await fs.getByLabel('Smallest silence').selectOption('5000'); await p.waitForTimeout(200);
  assert.match(await p.locator('main').innerText(), /Saved\./); assert.equal(await fs.getByLabel('Smallest silence').inputValue(), '5000'); ok('a change saves');
  // the review sheet: needs an open card for its media root
  await p.getByRole('button', { name: 'Library', exact: true }).click(); await p.waitForTimeout(500);
  if (!(await p.getByRole('button', { name: 'Settings', exact: true }).isVisible())) await p.getByRole('button', { name: /Tools & settings/ }).click();
  await p.getByRole('button', { name: 'Settings', exact: true }).click(); await p.waitForTimeout(500);
  await p.locator('fieldset', { hasText: 'Skip silence at the start and end' }).getByRole('button', { name: 'Review tracks…' }).click(); await p.waitForTimeout(500);
  const dlg = p.getByRole('dialog', { name: 'Tracks and what is skipped' });
  assert.match(await dlg.innerText(), /2 of 3 tracks have silence to skip/); ok('the review lists the tracks and counts those with silence');
  assert.match(await dlg.getByRole('button', { name: /01 Intro/ }).innerText(), /9\.8 s · 0\.0 s/); ok('lead and tail are shown per track');
  await dlg.getByRole('button', { name: /01 Intro/ }).click(); await p.waitForTimeout(400);
  assert.equal(await dlg.getByLabel('Seconds skipped at the start').inputValue(), '9.80'); ok('the editor opens on the detected start');
  await dlg.getByLabel('Seconds skipped at the start').fill('5'); await dlg.getByLabel('Seconds skipped at the start').dispatchEvent('change');
  await dlg.getByRole('button', { name: 'Save' }).click(); await p.waitForTimeout(700);
  assert.match(await dlg.getByRole('button', { name: /01 Intro/ }).innerText(), /5\.0 s/); assert.match(await dlg.innerText(), /edited/); ok('a typed value is saved and the track shows as edited');
  await dlg.getByLabel('Never skip silence on this track').check(); await dlg.getByRole('button', { name: 'Save' }).click(); await p.waitForTimeout(700);
  assert.match(await dlg.getByRole('button', { name: /01 Intro/ }).innerText(), /never skip/); assert.match(await dlg.innerText(), /1 of 3 tracks/); ok('never skip leaves the track whole');
  await dlg.getByRole('button', { name: 'Back to detected' }).click(); await p.waitForTimeout(700);
  assert.match(await dlg.getByRole('button', { name: /01 Intro/ }).innerText(), /9\.8 s/); ok('back to detected restores it');
  await dlg.getByRole('button', { name: 'Done' }).click(); await p.waitForTimeout(200);
  const fs2 = p.locator('fieldset', { hasText: 'Skip silence at the start and end' });
  await fs2.getByRole('button', { name: 'Turn off' }).click(); await p.waitForTimeout(200);
  assert.equal(await fs2.getByLabel('Silence level').count(), 0); ok('turning it off hides the options');
  assert.deepEqual(errors, []); ok('no page errors and no unmocked commands');
  console.log(`${passed} checks passed`); await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
