/// Looks up a canonical platform by ID or common alias (case-insensitive).
pub fn find(id: &str) -> Option<&'static PlatformSpec> {
    let lower = id.trim().to_ascii_lowercase();
    let canonical = match lower.as_str() {
        "gameboy" => "gb",
        "gameboycolor" => "gbc",
        "gameboyadvance" => "gba",
        "supernintendo" => "snes",
        "playstation" => "psx",
        "atari2600" => "2600",
        "atari5200" => "5200",
        "atari7800" => "7800",
        "megadrive" => "genesis",
        "sega32x" => "32x",
        "segacd" => "megacd",
        "gamegear" => "gg",
        "tg16" => "pce",
        "supergrafx" => "sgx",
        "pokemonmini" => "poke_mini",
        "cpc" => "amstrad",
        "ao486" => "dos",
        "ws" | "wsc" => "wonderswan",
        "zx" => "zxspectrum",
        "neogeo" => "ng",
        "mame" | "cps1" | "cps2" => "arcade",
        other => other,
    };
    PLATFORMS.iter().find(|p| p.id == canonical)
}

/// Infers a canonical platform from a core's ID, display name, or accepted ROM file extensions.
pub fn infer_from_core(
    core_id: &str,
    core_name: &str,
    extensions: &[String],
) -> Option<&'static PlatformSpec> {
    // Prefer unique extension matches first (excluding shared disc/generic formats like bin/cue/chd/iso).
    const UNIQUE_EXTS: &[(&str, &str)] = &[
        ("lnx", "lynx"),
        ("pce", "pce"),
        ("sgx", "sgx"),
        ("gg", "gg"),
        ("gba", "gba"),
        ("gbc", "gbc"),
        ("gb", "gb"),
        ("nds", "nds"),
        ("min", "poke_mini"),
        ("sfc", "snes"),
        ("smc", "snes"),
        ("nes", "nes"),
        ("fds", "nes"),
        ("adf", "amiga"),
        ("z64", "n64"),
        ("n64", "n64"),
        ("sms", "sms"),
        ("md", "genesis"),
        ("gen", "genesis"),
        ("32x", "32x"),
        ("a26", "2600"),
        ("a52", "5200"),
        ("a78", "7800"),
        ("j64", "jaguar"),
        ("sv", "supervision"),
        ("neo", "ng"),
        ("wsc", "wonderswan"),
        ("vec", "vectrex"),
        ("p8", "pico8"),
        ("mra", "arcade"),
        ("st", "atarist"),
        ("atr", "atari800"),
        ("woz", "apple2"),
        ("d88", "pc88"),
        ("dim", "x68000"),
    ];
    for ext in extensions {
        let clean = ext.trim().trim_start_matches('.').to_ascii_lowercase();
        if let Some((_, pid)) = UNIQUE_EXTS.iter().find(|(e, _)| *e == clean)
            && let Some(spec) = find(pid)
        {
            return Some(spec);
        }
    }

    let hay = format!("{} {}", core_id, core_name).to_ascii_lowercase();
    const TOKENS: &[(&[&str], &str)] = &[
        (&["lynx"], "lynx"),
        (&["game gear", "gamegear"], "gg"),
        (&["master system", "sms"], "sms"),
        (&["pcecd", "pc engine cd", "turbografx-cd"], "pcecd"),
        (&["supergrafx", "sgx"], "sgx"),
        (&["pce", "pc engine", "turbografx"], "pce"),
        (&["snes", "super nintendo"], "snes"),
        (&["nes", "famicom"], "nes"),
        (&["gba", "game boy advance"], "gba"),
        (&["gbc", "game boy color"], "gbc"),
        (&["game boy", "gameboy"], "gb"),
        (&["nintendo ds", "nds", "dspico"], "nds"),
        (&["32x", "sega 32x"], "32x"),
        (&["segacd", "sega cd", "megacd", "mega-cd"], "megacd"),
        (&["genesis", "mega drive", "megadrive"], "genesis"),
        (&["saturn"], "saturn"),
        (&["playstation", "psx"], "psx"),
        (&["amiga", "minimig"], "amiga"),
        (&["c64", "commodore 64"], "c64"),
        (&["atari st", "atarist"], "atarist"),
        (&["spectrum", "zxspectrum"], "zxspectrum"),
        (&["amstrad", "cpc"], "amstrad"),
        (&["ao486", "ms-dos", "dos"], "dos"),
        (&["x68000"], "x68000"),
        (&["pico-8", "pico8"], "pico8"),
        (&["3do"], "3do"),
        (&["arduboy"], "arduboy"),
    ];
    for (keys, pid) in TOKENS.iter().copied() {
        if keys.iter().any(|k| hay.contains(k))
            && let Some(spec) = find(pid)
        {
            return Some(spec);
        }
    }
    None
}

/// Returns every registered canonical platform in display order.
pub fn all() -> Vec<PlatformSpec> {
    PLATFORMS.to_vec()
}

