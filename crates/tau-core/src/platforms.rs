        assert_eq!(find("sega32x").unwrap().id, "32x");
        assert_eq!(find("segacd").unwrap().id, "megacd");
        assert_eq!(find("pokemonmini").unwrap().id, "poke_mini");
        assert_eq!(find("cpc").unwrap().id, "amstrad");
        assert_eq!(find("ao486").unwrap().id, "dos");
        assert_eq!(find("supergrafx").unwrap().id, "sgx");
        assert_eq!(find("ws").unwrap().id, "wonderswan");
        assert_eq!(find("mame").unwrap().id, "arcade");
        assert_eq!(find("tg16").unwrap().id, "pce");
        assert_eq!(find("zx").unwrap().id, "zxspectrum");
        assert_eq!(find("neogeo").unwrap().id, "ng");

