//! Canonical device-agnostic platform registry (`gb`, `gba`, `nds`, `snes`, `lynx`, etc.).
//!
//! Shared across Analogue Pocket, Game Bub, and future targets (MiSTer, DSpico) so ROMs, online
//! game art lookups (`libretro-database` / `libretro-thumbnails` / Homebrew Hub), and Marketplace
//! metadata speak one platform vocabulary.

